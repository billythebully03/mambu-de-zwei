-- =========================================
-- MEMBU DATABASE
-- =========================================

-- 1. История сообщений

create table if not exists public.membu_messages (
    chat_id bigint not null,
    message_id bigint not null,

    sender_id bigint,
    sender_name text not null default '',
    username text not null default '',

    text text not null default '',

    reply_to_user_id bigint,
    reply_to_message_id bigint,

    branch_id text,

    created_at timestamptz not null default now(),

    primary key (chat_id, message_id)
);


create index if not exists membu_messages_chat_created
on public.membu_messages (
    chat_id,
    created_at desc
);


create index if not exists membu_messages_branch
on public.membu_messages (
    chat_id,
    branch_id,
    created_at
);


-- 2. Ветки диалогов

create table if not exists public.membu_branches (
    branch_id text primary key,

    chat_id bigint not null,

    root_message_id bigint,
    root_sender_id bigint,

    active boolean not null default true,

    created_at timestamptz not null default now(),
    last_activity_at timestamptz not null default now(),
    last_ai_at timestamptz
);


create index if not exists membu_branches_chat_active
on public.membu_branches (
    chat_id,
    active,
    last_activity_at desc
);


-- 3. Долговременная память

create table if not exists public.membu_memories (
    id bigint generated by default as identity primary key,

    chat_id bigint not null,

    category text not null check (
        category in (
            'profile',
            'preference',
            'relationship',
            'ongoing',
            'event',
            'inside_joke',
            'opinion'
        )
    ),

    content text not null,

    importance integer not null default 3
        check (importance between 1 and 5),

    people text[] not null default '{}',

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    unique (chat_id, category, content)
);


create index if not exists membu_memories_chat
on public.membu_memories (chat_id);


create index if not exists membu_memories_category
on public.membu_memories (chat_id, category);


-- =========================================
-- 4. ПОИСК ВОСПОМИНАНИЙ
-- =========================================

-- Вызывается только через инструмент Gemini.
-- База не передаётся модели целиком.

create or replace function public.search_membu_memory(
    p_chat_id bigint,
    p_query text,
    p_category text default null,
    p_limit integer default 5
)
returns table (
    id bigint,
    category text,
    content text,
    importance integer,
    people text[]
)
language sql
stable
security definer
set search_path = public
as $$

    select
        m.id,
        m.category,
        m.content,
        m.importance,
        m.people

    from public.membu_memories m

    where
        m.chat_id = p_chat_id

        and (
            p_category is null
            or m.category = p_category
        )

        and to_tsvector(
            'simple',
            coalesce(m.content, '') || ' ' ||
            array_to_string(m.people, ' ')
        ) @@ websearch_to_tsquery(
            'simple',
            p_query
        )

    order by
        m.importance desc,

        ts_rank(
            to_tsvector(
                'simple',
                coalesce(m.content, '') || ' ' ||
                array_to_string(m.people, ' ')
            ),
            websearch_to_tsquery('simple', p_query)
        ) desc

    limit greatest(
        1,
        least(coalesce(p_limit, 5), 8)
    );

$$;


-- =========================================
-- 5. БЕЗОПАСНОСТЬ
-- =========================================

alter table public.membu_messages
enable row level security;

alter table public.membu_branches
enable row level security;

alter table public.membu_memories
enable row level security;


revoke all on public.membu_messages
from anon, authenticated;

revoke all on public.membu_branches
from anon, authenticated;

revoke all on public.membu_memories
from anon, authenticated;


grant all on public.membu_messages
to service_role;

grant all on public.membu_branches
to service_role;

grant all on public.membu_memories
to service_role;


grant usage, select on all sequences in schema public
to service_role;


revoke all on function public.search_membu_memory(
    bigint,
    text,
    text,
    integer
)
from public, anon, authenticated;


grant execute on function public.search_membu_memory(
    bigint,
    text,
    text,
    integer
)
to service_role;
