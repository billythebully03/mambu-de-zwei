-- =========================================
-- MEMBU: журнал редактирования собственных сообщений
-- Запустить один раз в Supabase SQL Editor.
-- =========================================

create table if not exists public.membu_message_edits (
    id bigint generated by default as identity primary key,

    chat_id bigint not null,
    message_id bigint not null,
    bot_user_id bigint not null,

    old_text text not null,
    new_text text not null,
    reason text not null default '',

    edited_at timestamptz not null default now()
);


create index if not exists membu_message_edits_chat_time
on public.membu_message_edits (
    chat_id,
    edited_at desc
);


create index if not exists membu_message_edits_message
on public.membu_message_edits (
    chat_id,
    message_id
);


-- =========================================
-- АТОМАРНАЯ ЗАПИСЬ РЕДАКТИРОВАНИЯ
-- =========================================

create or replace function public.record_membu_message_edit(
    p_chat_id bigint,
    p_message_id bigint,
    p_bot_user_id bigint,
    p_old_text text,
    p_new_text text,
    p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin

    if p_new_text is null or length(trim(p_new_text)) = 0 then
        return jsonb_build_object(
            'recorded', false,
            'reason', 'empty_new_text'
        );
    end if;

    if length(p_new_text) > 4000 then
        return jsonb_build_object(
            'recorded', false,
            'reason', 'text_too_long'
        );
    end if;


    -- Обновляем только сообщение с точным старым текстом,
    -- которое принадлежит указанному боту.

    update public.membu_messages
    set text = p_new_text
    where
        chat_id = p_chat_id
        and message_id = p_message_id
        and sender_id = p_bot_user_id
        and text = p_old_text;


    if not found then
        return jsonb_build_object(
            'recorded', false,
            'reason', 'message_changed_or_not_owned'
        );
    end if;


    -- Сохраняем первоначальную и новую версии.

    insert into public.membu_message_edits (
        chat_id,
        message_id,
        bot_user_id,
        old_text,
        new_text,
        reason,
        edited_at
    )
    values (
        p_chat_id,
        p_message_id,
        p_bot_user_id,
        p_old_text,
        p_new_text,
        coalesce(p_reason, ''),
        now()
    );


    return jsonb_build_object(
        'recorded', true,
        'message_id', p_message_id
    );

end;
$$;


-- =========================================
-- БЕЗОПАСНОСТЬ
-- =========================================

alter table public.membu_message_edits
enable row level security;


revoke all on public.membu_message_edits
from anon, authenticated;


grant all on public.membu_message_edits
to service_role;


grant usage, select
on sequence public.membu_message_edits_id_seq
to service_role;


revoke all on function public.record_membu_message_edit(
    bigint,
    bigint,
    bigint,
    text,
    text,
    text
)
from public, anon, authenticated;


grant execute on function public.record_membu_message_edit(
    bigint,
    bigint,
    bigint,
    text,
    text,
    text
)
to service_role;


