-- 1. Профиль общей манеры общения чата.

create table if not exists public.membu_chat_profiles (
    chat_id bigint primary key,
    style_profile text not null default '',
    observed_messages bigint not null default 0,
    last_analyzed_message_count bigint not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.membu_chat_profiles enable row level security;

revoke all on public.membu_chat_profiles
from anon, authenticated;

grant all on public.membu_chat_profiles
to service_role;


create or replace function public.bump_membu_chat_profile_message_count()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if coalesce(new.sender_name, '') <> 'Мембу' then
        insert into public.membu_chat_profiles (
            chat_id,
            observed_messages,
            updated_at
        )
        values (
            new.chat_id,
            1,
            now()
        )
        on conflict (chat_id)
        do update set
            observed_messages =
                public.membu_chat_profiles.observed_messages + 1,
            updated_at = now();
    end if;

    return new;
end;
$$;


-- Не удаляем существующий триггер:
-- создаём его только при отсутствии.

do $$
begin
    if not exists (
        select 1
        from pg_trigger
        where tgname = 'membu_count_chat_messages'
          and tgrelid = 'public.membu_messages'::regclass
          and not tgisinternal
    ) then
        create trigger membu_count_chat_messages
        after insert on public.membu_messages
        for each row
        execute function public.bump_membu_chat_profile_message_count();
    end if;
end;
$$;


revoke all on function public.bump_membu_chat_profile_message_count()
from public, anon, authenticated;

grant execute on function public.bump_membu_chat_profile_message_count()
to service_role;


-- 2. Журнал редактирования сообщений Мембу.

create table if not exists public.membu_message_edits (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    message_id bigint not null,
    bot_user_id bigint not null,
    old_text text not null,
    new_text text not null,
    reason text not null default '',
    edited_at timestamptz not null default now()
);


-- Одно сообщение можно внести в журнал только один раз.

create unique index if not exists membu_message_edits_once
on public.membu_message_edits (
    chat_id,
    message_id
);

create index if not exists membu_message_edits_chat_time
on public.membu_message_edits (
    chat_id,
    edited_at desc
);


-- 3. Пользователи, которые сами открыли личный чат с Мембу.
-- Запись появляется только после входящего сообщения пользователя.

create table if not exists public.membu_private_users (
    user_id bigint primary key,
    private_chat_id bigint not null,
    first_name text not null default '',
    username text not null default '',
    enabled boolean not null default true,
    last_seen_at timestamptz not null default now()
);


-- Переносим в список тех, кто уже писал Мембу в личку до этой доработки.
-- В группах Telegram chat_id отрицательный; private chat ID положительный.

insert into public.membu_private_users (
    user_id,
    private_chat_id,
    first_name,
    username,
    enabled,
    last_seen_at
)
select distinct on (m.chat_id)
    m.chat_id,
    m.chat_id,
    coalesce(m.sender_name, ''),
    coalesce(m.username, ''),
    true,
    m.created_at
from public.membu_messages m
where m.chat_id > 0
  and m.sender_id = m.chat_id
order by m.chat_id, m.created_at desc
on conflict (user_id) do nothing;


-- 4. Контакт группы на случай, если Мембу удалят.
-- Администратор назначает себя командой /membu_contact.

create table if not exists public.membu_chat_contacts (
    chat_id bigint primary key,
    user_id bigint not null,
    display_name text not null default '',
    username text not null default '',
    updated_at timestamptz not null default now(),
    last_notified_at timestamptz
);


-- 5. Атомарное сохранение истории редактирования.
-- Обновляет только запись с прежним текстом и точным ID бота.

create or replace function public.record_membu_message_edit(
    p_chat_id bigint,
    p_message_id bigint,
    p_bot_user_id bigint,
    p_old_text text,
    p_new_text text,
    p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
    if p_new_text is null or length(trim(p_new_text)) = 0 then
        return jsonb_build_object(
            'recorded', false,
            'reason', 'empty_new_text'
        );
    end if;

    if length(p_new_text) > 4000 then
        return jsonb_build_object(
            'recorded', false,
            'reason', 'text_too_long'
        );
    end if;

    update public.membu_messages
    set text = p_new_text
    where chat_id = p_chat_id
      and message_id = p_message_id
      and sender_id = p_bot_user_id
      and text = p_old_text;

    if not found then
        return jsonb_build_object(
            'recorded', false,
            'reason', 'message_changed_or_not_owned'
        );
    end if;

    insert into public.membu_message_edits (
        chat_id,
        message_id,
        bot_user_id,
        old_text,
        new_text,
        reason,
        edited_at
    )
    values (
        p_chat_id,
        p_message_id,
        p_bot_user_id,
        p_old_text,
        p_new_text,
        coalesce(p_reason, ''),
        now()
    );

    return jsonb_build_object(
        'recorded', true,
        'message_id', p_message_id
    );
end;
$$;


-- 6. Возвращает контакт для однократного сообщения после исключения.
-- Одно уведомление на группу не чаще одного раза за 24 часа.

create or replace function public.claim_membu_removal_notice(
    p_chat_id bigint
)
returns table (
    user_id bigint,
    display_name text,
    username text
)
language sql
security definer
set search_path = public
as $$
    update public.membu_chat_contacts c
    set last_notified_at = now()
    where c.chat_id = p_chat_id
      and (
          c.last_notified_at is null
          or c.last_notified_at < now() - interval '24 hours'
      )
    returning
        c.user_id,
        c.display_name,
        c.username;
$$;


